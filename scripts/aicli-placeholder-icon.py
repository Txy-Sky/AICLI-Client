#!/usr/bin/env python3
"""Draw the temporary AI icon with only Python's standard library.

Then run pnpm tauri icon scripts/assets/aicli-placeholder.png --output src-tauri/icons.
The tray templates and DMG background are not generated by the Tauri CLI.
"""

from pathlib import Path
import struct
import zlib


ROOT = Path(__file__).resolve().parents[1]
GLYPHS = ("011100111", "110110010", "110110010", "111110010",
          "110110010", "110110010", "110110111")


def draw(path, width, height, template=False):
    scale = max(1, min(width // 13, height // 11))
    left, top = (width - 9 * scale) // 2, (height - 7 * scale) // 2
    background = bytes((0, 0, 0, 0) if template else (37, 99, 235, 255))
    foreground = bytes((0, 0, 0, 255) if template else (255, 255, 255, 255))
    rows = []
    for y in range(height):
        row = bytearray(background * width)
        gy = (y - top) // scale
        if 0 <= gy < 7:
            for gx, pixel in enumerate(GLYPHS[gy]):
                if pixel == "1":
                    start = (left + gx * scale) * 4
                    row[start:start + scale * 4] = foreground * scale
        rows.append(b"\x00" + row)

    def chunk(kind, data):
        return (struct.pack(">I", len(data)) + kind + data
                + struct.pack(">I", zlib.crc32(kind + data)))

    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_bytes(b"\x89PNG\r\n\x1a\n"
                     + chunk(b"IHDR", struct.pack(">IIBBBBB", width, height, 8, 6, 0, 0, 0))
                     + chunk(b"IDAT", zlib.compress(b"".join(rows), 9))
                     + chunk(b"IEND", b""))
    print(f"Generated {path.relative_to(ROOT)}: {width}x{height}")


if __name__ == "__main__":
    draw(ROOT / "scripts/assets/aicli-placeholder.png", 1024, 1024)
    draw(ROOT / "src-tauri/icons/dmg-background.png", 1320, 800)
    for path in sorted((ROOT / "src-tauri/icons/tray/macos").glob("*.png")):
        width, height = struct.unpack(">II", path.read_bytes()[16:24])
        draw(path, width, height, template=True)
