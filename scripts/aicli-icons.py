#!/usr/bin/env python3
"""Build the app icon sources from assets/aicli-logo.png with only the standard library.

    python3 scripts/aicli-icons.py
    pnpm tauri icon scripts/assets/aicli-icon-source.png --output src-tauri/icons
    python3 scripts/aicli-icons.py --normalize-icns

Outputs (replacing the B-08 placeholder "AI" icon):
- scripts/assets/aicli-icon-source.png: 1024 white rounded tile with a thin border and the
  logo centred, 56 px transparent margin (macOS icon grid). `tauri icon` makes every size.
- src/assets/icons/aicli-logo.png: 512 full-bleed tile used inside the app.
- src-tauri/icons/tray/macos/*.png: black silhouette templates (follow the menu bar colour).
- src-tauri/icons/dmg-background.png: plain light background for the DMG window.
The tray templates, the in-app logo and the DMG background are not generated by the Tauri CLI.
"""

from pathlib import Path
import struct
import sys
import zlib

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "assets/aicli-logo.png"


def read_png(path):
    """Decode an 8-bit RGB or RGBA, non-interlaced PNG into rows of RGB tuples."""
    data = path.read_bytes()
    assert data[:8] == b"\x89PNG\r\n\x1a\n", path
    offset, idat = 8, b""
    while offset < len(data):
        length = struct.unpack(">I", data[offset:offset + 4])[0]
        kind = data[offset + 4:offset + 8]
        body = data[offset + 8:offset + 8 + length]
        if kind == b"IHDR":
            width, height, depth, color, _, _, interlace = struct.unpack(">IIBBBBB", body)
            assert depth == 8 and color in (2, 6) and interlace == 0, "8-bit RGB(A) only"
        elif kind == b"IDAT":
            idat += body
        offset += 12 + length
    bpp = 3 if color == 2 else 4
    raw = zlib.decompress(idat)
    stride = width * bpp
    rows, previous = [], bytearray(stride)
    for y in range(height):
        start = y * (stride + 1)
        kind, line = raw[start], bytearray(raw[start + 1:start + 1 + stride])
        for i in range(stride):
            left = line[i - bpp] if i >= bpp else 0
            up = previous[i]
            corner = previous[i - bpp] if i >= bpp else 0
            if kind == 1:
                line[i] = (line[i] + left) & 255
            elif kind == 2:
                line[i] = (line[i] + up) & 255
            elif kind == 3:
                line[i] = (line[i] + (left + up) // 2) & 255
            elif kind == 4:
                p = left + up - corner
                pa, pb, pc = abs(p - left), abs(p - up), abs(p - corner)
                pred = left if pa <= pb and pa <= pc else up if pb <= pc else corner
                line[i] = (line[i] + pred) & 255
        rows.append(line)
        previous = line
    return width, height, bpp, rows


def write_png(path, width, height, pixels):
    """pixels: bytearray RGBA, row-major."""
    raw = b"".join(b"\x00" + bytes(pixels[y * width * 4:(y + 1) * width * 4]) for y in range(height))

    def chunk(kind, body):
        return struct.pack(">I", len(body)) + kind + body + struct.pack(">I", zlib.crc32(kind + body))

    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_bytes(b"\x89PNG\r\n\x1a\n"
                     + chunk(b"IHDR", struct.pack(">IIBBBBB", width, height, 8, 6, 0, 0, 0))
                     + chunk(b"IDAT", zlib.compress(raw, 9))
                     + chunk(b"IEND", b""))
    print(f"Generated {path.relative_to(ROOT)}: {width}x{height}")


class Logo:
    def __init__(self, path):
        self.width, self.height, bpp, rows = read_png(path)
        # Summed-area tables per channel: area averages in O(1) when scaling down.
        w, h = self.width, self.height
        self.tables = []
        for channel in range(3):
            table = [[0] * (w + 1) for _ in range(h + 1)]
            for y in range(h):
                row, above, line, running = table[y + 1], table[y], rows[y], 0
                for x in range(w):
                    running += line[x * bpp + channel]
                    row[x + 1] = above[x + 1] + running
            self.tables.append(table)
        # Content box: pixels clearly darker than the white background.
        xs, ys = [], []
        for y in range(h):
            line = rows[y]
            for x in range(w):
                if min(line[x * bpp], line[x * bpp + 1], line[x * bpp + 2]) < 225:
                    xs.append(x)
                    ys.append(y)
        self.box = (min(xs), min(ys), max(xs), max(ys))
        print(f"Logo {w}x{h}, content box {self.box}")

    def average(self, x0, y0, x1, y1):
        """Mean RGB over the source rectangle [x0, x1) x [y0, y1), clipped; white outside."""
        ix0, iy0 = max(0, int(x0)), max(0, int(y0))
        ix1, iy1 = min(self.width, max(ix0 + 1, int(x1 + 0.999))), min(self.height, max(iy0 + 1, int(y1 + 0.999)))
        if ix0 >= self.width or iy0 >= self.height or ix1 <= 0 or iy1 <= 0:
            return (255.0, 255.0, 255.0)
        area = (ix1 - ix0) * (iy1 - iy0)
        return tuple((t[iy1][ix1] - t[iy0][ix1] - t[iy1][ix0] + t[iy0][ix0]) / area for t in self.tables)

    def sampler(self, size, scale):
        """Map output pixel (x, y) in a size x size canvas to the source, logo centred."""
        x0, y0, x1, y1 = self.box
        cx, cy = (x0 + x1) / 2, (y0 + y1) / 2
        step = 1 / scale

        def at(x, y):
            sx = cx + (x - size / 2) / scale
            sy = cy + (y - size / 2) / scale
            return self.average(sx, sy, sx + step, sy + step)
        return at

    @property
    def extent(self):
        x0, y0, x1, y1 = self.box
        return max(x1 - x0 + 1, y1 - y0 + 1)


def rounded_cover(x, y, left, top, size, radius):
    """Coverage of pixel (x, y) by a rounded square, 4x4 supersampled."""
    # Fast paths: well inside or well outside the straight edges.
    rx, ry = x - left, y - top
    if rx < -1 or ry < -1 or rx > size + 1 or ry > size + 1:
        return 0.0
    if radius + 1 <= rx <= size - radius - 2 or radius + 1 <= ry <= size - radius - 2:
        if 1 <= rx <= size - 2 and 1 <= ry <= size - 2:
            return 1.0
    hit = 0
    for sy in range(4):
        for sx in range(4):
            px, py = rx + (sx + 0.5) / 4, ry + (sy + 0.5) / 4
            if px < 0 or py < 0 or px > size or py > size:
                continue
            qx = max(radius - px, 0.0, px - (size - radius))
            qy = max(radius - py, 0.0, py - (size - radius))
            if qx * qx + qy * qy <= radius * radius:
                hit += 1
    return hit / 16


def tile(logo, size, margin, content_ratio):
    pixels = bytearray(size * size * 4)
    tile_size = size - 2 * margin
    radius = tile_size * 0.225
    stroke = max(1, size / 256)
    at = logo.sampler(size, tile_size * content_ratio / logo.extent)
    for y in range(size):
        for x in range(size):
            outer = rounded_cover(x, y, margin, margin, tile_size, radius)
            if outer == 0:
                continue
            inner = rounded_cover(x, y, margin + stroke, margin + stroke, tile_size - 2 * stroke, radius - stroke)
            r, g, b = at(x, y)
            edge = 1 - inner / outer
            i = (y * size + x) * 4
            pixels[i] = round(r * (1 - edge) + 0xDD * edge)
            pixels[i + 1] = round(g * (1 - edge) + 0xDD * edge)
            pixels[i + 2] = round(b * (1 - edge) + 0xE3 * edge)
            pixels[i + 3] = round(255 * outer)
    return pixels


def template(logo, width, height, pad):
    """Black silhouette for the macOS menu bar; alpha from the distance to white.

    The source's white background is slightly noisy (up to ~12 below 255): that much is cut
    off so the template has no faint haze around the mark."""
    size = max(width, height)
    pixels = bytearray(width * height * 4)
    at = logo.sampler(size, (min(width, height) - 2 * pad) / logo.extent)
    dx, dy = (size - width) / 2, (size - height) / 2
    for y in range(height):
        for x in range(width):
            r, g, b = at(x + dx, y + dy)
            pixels[(y * width + x) * 4 + 3] = round(min(255.0, max(0.0, (255 - min(r, g, b) - 14) * 2.6)))
    return pixels


def solid(width, height, rgba):
    return bytearray(bytes(rgba) * (width * height))


def normalize_icns():
    # Tauri's ICNS writer iterates a HashMap: chunk order varies per process.
    # Preserve every chunk byte while assigning a deterministic container order.
    path = ROOT / "src-tauri/icons/icon.icns"
    content = path.read_bytes()
    assert content[:4] == b"icns"
    assert struct.unpack(">I", content[4:8])[0] == len(content)
    chunks, offset = [], 8
    while offset < len(content):
        size = struct.unpack(">I", content[offset + 4:offset + 8])[0]
        assert size >= 8 and offset + size <= len(content)
        chunks.append(content[offset:offset + size])
        offset += size
    assert offset == len(content)
    normalized = content[:8] + b"".join(sorted(chunks))
    assert len(normalized) == len(content)
    path.write_bytes(normalized)
    print(f"Normalized ICNS: {len(chunks)} complete chunks; all payloads retained")


def main():
    logo = Logo(SOURCE)
    write_png(ROOT / "scripts/assets/aicli-icon-source.png", 1024, 1024, tile(logo, 1024, 56, 0.72))
    write_png(ROOT / "src/assets/icons/aicli-logo.png", 512, 512, tile(logo, 512, 0, 0.74))
    for path in sorted((ROOT / "src-tauri/icons/tray/macos").glob("*.png")):
        width, height = struct.unpack(">II", path.read_bytes()[16:24])
        write_png(path, width, height, template(logo, width, height, max(4, min(width, height) // 18)))
    # The DMG window background: the page colour of the light theme.
    write_png(ROOT / "src-tauri/icons/dmg-background.png", 1320, 800, solid(1320, 800, (0xF5, 0xF5, 0xF7, 0xFF)))


if __name__ == "__main__" and sys.argv[1:] == ["--normalize-icns"]:
    normalize_icns()
elif __name__ == "__main__":
    assert not sys.argv[1:], "Only --normalize-icns is supported"
    main()
