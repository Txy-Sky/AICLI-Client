const remote = (
  id: string,
  title: string,
  publisher: string,
  icon: string | undefined,
  url: string,
  homepage: string,
  description: string,
  options: { signIn?: boolean; inputs?: McpCatalogInput[] } = {},
): McpCatalogEntry => ({
  id,
  title,
  publisher,
  icon,
  homepage,
  description,
  spec: { type: "http", url },
  signIn: options.signIn,
  inputs: options.inputs ?? [],
  source: "featured",
});

const local = (
  id: string,
  title: string,
  publisher: string,
  icon: string | undefined,
  homepage: string,
  description: string,
  runs: "npx" | "uvx",
  pkg: string,
  inputs: McpCatalogInput[] = [],
): McpCatalogEntry => ({
  id,
  title,
  publisher,
  icon,
  homepage,
  description,
  spec: (runs === "npx"
    ? { type: "stdio", ...createNpxCommand(pkg, ["-y"]) }
    : { type: "stdio", command: "uvx", args: [pkg] }) as McpServerSpec,
  runs,
  inputs,
  source: "featured",
});

const secretEnv = (key: string, obtain: string): McpCatalogInput => ({
  key,
  where: "env",
  labelKey: "apiKey",
  obtain,
  secret: true,
  required: true,
});

