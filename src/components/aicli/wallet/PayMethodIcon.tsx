/**
 * 支付方式图标：支付宝、微信用官方标志；其他方式没有可用的官方图形，
 * 用首字色块代替。图形不读出，名字由旁边的文字给出。
 */
export function PayMethodIcon({ method }: { method: AicliPayMethod }) {
  const brand = payMethodBrand(method.type);
  if (brand) {
    return (
      <svg
        aria-hidden="true"
        data-brand={brand}
        viewBox="0 0 24 24"
        fill={BRANDS[brand].color}
        className="h-[22px] w-[22px] shrink-0"
      >
        <path d={BRANDS[brand].path} />
      </svg>
    );
  }
  const mark = payMethodMark(method.type, method.name);
  return (
    <span
      aria-hidden="true"
      style={{ backgroundColor: mark.color }}
      className="inline-flex h-[22px] w-[22px] shrink-0 items-center justify-center rounded-control text-caption font-bold text-white"
    >
      {mark.letter}
    </span>
  );
}
